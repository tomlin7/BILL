use bootloader_api::info::{FrameBuffer, FrameBufferInfo, PixelFormat};
use core::fmt;
use spin::Mutex;

pub static WRITER: Mutex<Option<Writer>> = Mutex::new(None);

#[allow(dead_code)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum Color {
    Black = 0,
    Blue = 1,
    Green = 2,
    Cyan = 3,
    Red = 4,
    Magenta = 5,
    Brown = 6,
    LightGray = 7,
    DarkGray = 8,
    LightBlue = 9,
    LightGreen = 10,
    LightCyan = 11,
    LightRed = 12,
    Pink = 13,
    Yellow = 14,
    White = 15,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
struct ColorCode(u8);

impl ColorCode {
    fn new(foreground: Color, background: Color) -> ColorCode {
        ColorCode((background as u8) << 4 | (foreground as u8))
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(C)]
struct ScreenChar {
    ascii_character: u8,
    color_code: ColorCode,
}

const BUFFER_HEIGHT: usize = 25;
const BUFFER_WIDTH: usize = 80;

#[repr(transparent)]
struct Buffer {
    chars: [[ScreenChar; BUFFER_WIDTH]; BUFFER_HEIGHT],
}

struct FbState {
    buf: &'static mut [u8],
    info: FrameBufferInfo,
    fg: [u8; 3],
    bg: [u8; 3],
}

pub struct Writer {
    column_position: usize,
    color_code: ColorCode,
    buffer: &'static mut Buffer,
    fb: Option<FbState>,
}

impl Writer {
    pub fn write_byte(&mut self, byte: u8) {
        match byte {
            b'\n' => self.new_line(),
            byte => {
                if self.column_position >= BUFFER_WIDTH {
                    self.new_line();
                }

                let row = BUFFER_HEIGHT - 1;
                let col = self.column_position;

                let color_code = self.color_code;
                unsafe {
                    core::ptr::write_volatile(
                        &mut self.buffer.chars[row][col],
                        ScreenChar {
                            ascii_character: byte,
                            color_code,
                        },
                    );
                }

                if let Some(ref mut fb) = self.fb {
                    let char_x = col * 8;
                    let char_y = row * 16;
                    fb.draw_char(byte, char_x, char_y, color_code);
                }

                self.column_position += 1;
            }
        }
    }

    pub fn write_string(&mut self, s: &str) {
        for byte in s.bytes() {
            match byte {
                0x20..=0x7e | b'\n' => self.write_byte(byte),
                _ => self.write_byte(0xfe),
            }
        }
    }

    fn new_line(&mut self) {
        for row in 1..BUFFER_HEIGHT {
            for col in 0..BUFFER_WIDTH {
                let character = unsafe { core::ptr::read_volatile(&self.buffer.chars[row][col]) };
                unsafe {
                    core::ptr::write_volatile(&mut self.buffer.chars[row - 1][col], character);
                }
            }
        }
        self.clear_row(BUFFER_HEIGHT - 1);
        self.column_position = 0;
    }

    fn clear_row(&mut self, row: usize) {
        let blank = ScreenChar {
            ascii_character: b' ',
            color_code: self.color_code,
        };
        for col in 0..BUFFER_WIDTH {
            unsafe {
                core::ptr::write_volatile(&mut self.buffer.chars[row][col], blank);
            }
        }
    }
}

impl fmt::Write for Writer {
    fn write_str(&mut self, s: &str) -> fmt::Result {
        self.write_string(s);
        Ok(())
    }
}

pub fn init(phys_mem_offset: u64, framebuffer: Option<FrameBuffer>) {
    let buffer = unsafe { &mut *((phys_mem_offset + 0xb8000) as *mut Buffer) };
    let fb = framebuffer.map(|fb| {
        let info = fb.info();
        let buf = fb.into_buffer();
        let fg = fb_color(info.pixel_format, 255, 255, 255);
        let bg = fb_color(info.pixel_format, 0, 0, 0);
        FbState { buf, info, fg, bg }
    });
    let writer = Writer {
        column_position: 0,
        color_code: ColorCode::new(Color::Yellow, Color::Black),
        buffer,
        fb,
    };
    *WRITER.lock() = Some(writer);
}

fn fb_color(fmt: PixelFormat, r: u8, g: u8, b: u8) -> [u8; 3] {
    match fmt {
        PixelFormat::Rgb => [r, g, b],
        PixelFormat::Bgr => [b, g, r],
        _ => [r, g, b],
    }
}

fn fb_color_from_vga(fmt: PixelFormat, color: ColorCode) -> [u8; 3] {
    let v = color.0;
    let bright = (v >> 3) & 1;
    let index = v & 0b111;
    let level = if bright == 1 { 255u8 } else { 170u8 };
    let (r, g, b) = match index {
        0 => (0, 0, 0),
        1 => (0, 0, level),
        2 => (0, level, 0),
        3 => (0, level, level),
        4 => (level, 0, 0),
        5 => (level, 0, level),
        6 => (level, level / 2, 0),
        7 => (level, level, level),
        _ => (level, level, level),
    };
    fb_color(fmt, r, g, b)
}

impl FbState {
    fn draw_char(&mut self, ch: u8, x: usize, y: usize, color_code: ColorCode) {
        let font_row = (ch as usize) * 16;
        let bpp = self.info.bytes_per_pixel;
        let stride = self.info.stride;
        let fg = fb_color_from_vga(self.info.pixel_format, color_code);
        let bg = bg_color_from_vga(self.info.pixel_format, color_code);
        for row in 0..16 {
            let bits = FONT_8X16[font_row + row];
            for col in 0..8 {
                let on = (bits >> (7 - col)) & 1 == 1;
                let color = if on { &fg } else { &bg };
                let px = x + col;
                let py = y + row;
                if px < self.info.width && py < self.info.height {
                    let offset = (py * stride + px) * bpp;
                    if offset + 2 < self.buf.len() {
                        self.buf[offset] = color[0];
                        self.buf[offset + 1] = color[1];
                        self.buf[offset + 2] = color[2];
                    }
                }
            }
        }
    }
}

fn bg_color_from_vga(fmt: PixelFormat, color: ColorCode) -> [u8; 3] {
    let index = (color.0 >> 4) & 0b111;
    let level = 0u8;
    let (r, g, b) = match index {
        0 => (0, 0, 0),
        1 => (0, 0, level),
        2 => (0, level, 0),
        3 => (0, level, level),
        4 => (level, 0, 0),
        5 => (level, 0, level),
        6 => (level, level / 2, 0),
        7 => (level, level, level),
        _ => (level, level, level),
    };
    fb_color(fmt, r, g, b)
}

#[doc(hidden)]
pub fn _print(args: fmt::Arguments) {
    use core::fmt::Write;
    let mut writer = WRITER.lock();
    if let Some(ref mut w) = *writer {
        w.write_fmt(args).unwrap();
    }
}

